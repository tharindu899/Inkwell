import com.inkwell.notes.editor.SourceEdit

var fails = 0
fun check(name: String, ok: Boolean, extra: String = "") { if (!ok) { fails++; println("FAIL $name $extra") } else println("ok   $name") }

fun main() {
    var r = SourceEdit.wrap("hello world", 0, 5, "**")
    check("bold wrap", r.text == "**hello** world" && r.start == 2 && r.end == 7, r.text)
    r = SourceEdit.wrap(r.text, r.start, r.end, "**")
    check("bold unwrap outside", r.text == "hello world" && r.start == 0 && r.end == 5, r.text)
    r = SourceEdit.wrap("**hi** x", 0, 6, "**")
    check("unwrap inside", r.text == "hi x", r.text)
    r = SourceEdit.wrap("ab", 1, 1, "*")
    check("collapsed", r.text == "a**b" && r.start == 2 && r.end == 2, r.text)
    r = SourceEdit.wrap("x y", 0, 1, "<u>", "</u>")
    check("tags", r.text == "<u>x</u> y", r.text)
    r = SourceEdit.wrap("abc", 3, 0, "`")
    check("reversed sel", r.text == "`abc`", r.text)

    r = SourceEdit.linePrefix("one\ntwo", 0, 7, "- ")
    check("bullets", r.text == "- one\n- two", r.text)
    r = SourceEdit.linePrefix(r.text, r.start, r.end, "- ")
    check("bullets toggle off", r.text == "one\ntwo", r.text)
    r = SourceEdit.linePrefix("# Title", 0, 0, "## ")
    check("replace heading", r.text == "## Title", r.text)
    r = SourceEdit.linePrefix("a\nb\nc", 0, 5, "1. ", numbered = true)
    check("numbers", r.text == "1. a\n2. b\n3. c", r.text)
    r = SourceEdit.linePrefix("a\nb\nc", 2, 2, "> ")
    check("middle line only", r.text == "a\n> b\nc", r.text)
    r = SourceEdit.linePrefix("- [x] done", 0, 3, "")
    check("to paragraph", r.text == "done", r.text)
    r = SourceEdit.linePrefix("task", 0, 0, "- [ ] ")
    check("task", r.text == "- [ ] task", r.text)
    r = SourceEdit.linePrefix("", 0, 0, "- ")
    check("empty doc", r.text == "- ", r.text)
    r = SourceEdit.linePrefix("a\n", 2, 2, "- ")
    check("caret on trailing empty line", r.text == "a\n- ", r.text)

    r = SourceEdit.indent("a\nb", 0, 3, 1)
    check("indent", r.text == "  a\n  b", r.text)
    r = SourceEdit.indent(r.text, r.start, r.end, -1)
    check("outdent", r.text == "a\nb", r.text)

    r = SourceEdit.insert("abcd", 1, 3, "XY")
    check("insert replaces sel", r.text == "aXYd" && r.start == 3, r.text)
    r = SourceEdit.insertBlock("para", 2, 2, "---")
    check("block after para", r.text == "para\n\n---\n", r.text)
    r = SourceEdit.insertBlock("a\n\nb", 0, 0, "---")
    check("block between", r.text == "a\n\n---\n\nb", r.text)
    r = SourceEdit.codeFence("x = 1", 0, 5)
    check("fence", r.text == "```\nx = 1\n```", r.text)
    r = SourceEdit.codeFence(r.text, 0, r.text.length)
    check("unfence", r.text == "x = 1", r.text)
    r = SourceEdit.clearInline("a **b** ~~c~~ `d` <u>e</u> *f* g", 0, 33)
    check("clear inline", r.text == "a b c d e f g", r.text)
    println(if (fails == 0) "ALL OK" else "$fails FAILED")
}
